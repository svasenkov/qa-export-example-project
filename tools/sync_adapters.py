#!/usr/bin/env python3
"""Validate this harness and generate Cline copies from .agents/skills.

Python standard library only. --check never writes files. This is a structural
check, not a test of agent discovery, behavior, project commands or coverage.
The small frontmatter format used here is name/description with plain, JSON
quoted, or folded values; this is deliberately not a general YAML parser.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parent.parent
GENERATED = "<!-- Generated by tools/sync_adapters.py; edit AGENTS.md or .agents/skills instead. -->"


def metadata(path: Path) -> dict[str, str]:
    text = path.read_text(encoding="utf-8")
    match = re.match(r"\A---\n(.*?)\n---(?:\n|$)", text, re.S)
    if not match:
        raise ValueError(f"{path}: missing or unclosed frontmatter")
    values: dict[str, str] = {}
    lines = iter(match[1].splitlines())
    current = None
    for line in lines:
        if not line.strip():
            continue
        if line.startswith(" "):
            if current is None:
                raise ValueError(f"{path}: unexpected indented metadata")
            values[current] += " " + line.strip()
            continue
        key, sep, raw = line.partition(":")
        if not sep or key not in {"name", "description"} or key in values:
            raise ValueError(f"{path}: unsupported or duplicate metadata field {key!r}")
        raw = raw.strip()
        current = key if raw in {">", ">-", "|", "|-"} else None
        if current:
            values[key] = ""
        elif raw.startswith('"'):
            value = json.loads(raw)
            if not isinstance(value, str):
                raise ValueError(f"{path}: {key} must be a string")
            values[key] = value
        else:
            values[key] = raw
    values = {key: value.strip() for key, value in values.items()}
    name = values.get("name", "")
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", name) or len(name) > 64:
        raise ValueError(f"{path}: invalid skill name")
    if name != path.parent.name:
        raise ValueError(f"{path}: name differs from directory")
    if not values.get("description"):
        raise ValueError(f"{path}: empty description")
    return values


def validate_links(root: Path, paths: list[Path]) -> None:
    """Check inline Markdown file links used by these documents, outside fences.

    Does not validate external URLs, heading anchors or backtick prose paths.
    """
    for path in paths:
        text = re.sub(r"^```[^\n]*\n.*?^```[^\n]*$", "", path.read_text(encoding="utf-8"), flags=re.M | re.S)
        for target in re.findall(r"\]\(([^\s)]+)\)", text):
            url = urlsplit(target.strip("<>"))
            if url.scheme or url.netloc or not url.path:
                continue
            candidate = (path.parent / unquote(url.path)).resolve()
            if not candidate.is_relative_to(root.resolve()) or not candidate.exists():
                raise ValueError(f"{path.relative_to(root)}: missing or external local link {target}")


def plan(root: Path) -> dict[Path, str]:
    source = root / ".agents/skills"
    skills = sorted(source.glob("*/SKILL.md"))
    if not skills:
        raise ValueError("No skills found in .agents/skills")
    docs = [root / "AGENTS.md", root / "README.md", root / "docs/coverage-profile.md", *sorted((root / "docs/qa").glob("*.md"))]
    for path in docs:
        if not path.is_file():
            raise ValueError(f"Missing required document: {path.relative_to(root)}")
    result: dict[Path, str] = {}
    names = []
    for path in skills:
        meta = metadata(path)
        names.append(meta["name"])
        result[root / ".cline/skills" / meta["name"] / "SKILL.md"] = path.read_text(encoding="utf-8")
    validate_links(root, [*docs, *skills])
    result[root / ".clinerules"] = (
        GENERATED + "\n\n"
        "Прочитай [AGENTS.md](AGENTS.md) перед работой в этом проекте.\n"
        "Skills для Cline находятся в `.cline/skills/`; исходники — в `.agents/skills/`.\n"
        "Генерируемые копии не редактируй вручную.\n"
        + "Доступные процедуры: " + ", ".join(f"`{name}`" for name in names) + ".\n"
    )
    extras = set((root / ".cline/skills").glob("*/SKILL.md")) - set(result)
    if extras:
        raise ValueError("Unexpected Cline skills; review before removing: " + ", ".join(str(p.relative_to(root)) for p in sorted(extras)))
    return result


def sync(root: Path, check: bool) -> list[str]:
    expected = plan(root)  # Validate everything before writing anything.
    stale = []
    for path, content in expected.items():
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        stale.append(str(path.relative_to(root)))
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    return stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="validate without writing")
    args = parser.parse_args()
    try:
        stale = sync(ROOT, args.check)
    except (ValueError, OSError) as error:
        print(f"ERROR: {error}")
        return 1
    if args.check and stale:
        print("Stale or missing adapters; run python3 tools/sync_adapters.py:")
        print("\n".join(stale))
        return 1
    print("OK: skill metadata, local file links and Cline copies checked." if args.check else f"Updated {len(stale)} adapter files.")
    print("Agent discovery, behavior and test commands were not executed by this check.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
